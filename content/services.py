# SERVICES에 "피부": {...} 형태로 넣고 CONTENT_SERVICE=피부로 전환합니다.
# 채우지 않은 항목이 있으면 그 분야의 글은 생성되지 않습니다(빈 사실로 글을 쓰지 않기 위함).
_TEMPLATE = {
    "label": "",
    "categories": [],
    "core_keywords": {},
    "category_signals": [],
    "scope": {"primary": [], "umbrella": "", "related": []},
    "differential": [],
    "devices": [],
    "steps": [],
    "strengths": [],
    "not_performed": [],
    "avoid_terms": [],
    "notice": [],
    "hashtags": [],
}

REQUIRED_KEYS = [
    "label", "categories", "core_keywords", "category_signals",
    "scope", "devices", "steps", "strengths", "notice", "hashtags",
]


class ServiceError(RuntimeError):
    pass


def available() -> list:
    return sorted(SERVICES.keys())


def get(name: str = "") -> dict:
    """진료 분야 설정을 가져온다."""
    name = name or ACTIVE
    if name not in SERVICES:
        raise ServiceError(
            f"'{name}' 진료 분야가 정의되어 있지 않습니다. "
            f"사용 가능: {', '.join(available())}\n"
            "content/services.py의 SERVICES에 추가하세요."
        )
    service = SERVICES[name]
    missing = [k for k in REQUIRED_KEYS if not service.get(k)]
    if missing:
        raise ServiceError(
            f"'{name}' 진료 분야 설정이 비어 있습니다: {', '.join(missing)}\n"
            "빈 사실로 글을 쓰지 않기 위해 생성을 막습니다. "
            "content/services.py를 채우세요."
        )
    return service


def current() -> dict:
    return get(ACTIVE)
